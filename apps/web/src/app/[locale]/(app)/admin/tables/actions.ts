"use server";

import { revalidatePath } from "next/cache";
import { getLocale } from "next-intl/server";
import type { PostgrestError } from "@supabase/supabase-js";
import { createServerSupabase } from "@/lib/supabase/server";

export type TableActionState = {
  error?: "labelRequired" | "duplicateLabel" | "forbidden" | "generic";
  /** Bumped on success so forms can reset. */
  done?: number;
};

const MAX_LABEL = 30;

function mapError(error: PostgrestError): NonNullable<TableActionState["error"]> {
  if (error.code === "23505") return "duplicateLabel";
  if (error.code === "42501") return "forbidden";
  return "generic";
}

async function revalidate() {
  const locale = await getLocale();
  revalidatePath(`/${locale}/admin/tables`);
  revalidatePath(`/${locale}/admin/tables/print`);
}

/** Create a table. The join code is generated by the DB; a (rare) global collision is retried. */
export async function createTable(
  _prev: TableActionState,
  formData: FormData,
): Promise<TableActionState> {
  const venueId = String(formData.get("venueId") ?? "");
  const label = String(formData.get("label") ?? "")
    .trim()
    .slice(0, MAX_LABEL);
  if (!label) return { error: "labelRequired" };

  const supabase = await createServerSupabase();
  if (!supabase || !venueId) return { error: "generic" };

  for (let attempt = 0; attempt < 3; attempt++) {
    const { error } = await supabase.from("venue_tables").insert({ venue_id: venueId, label });
    if (!error) {
      await revalidate();
      return { done: Date.now() };
    }
    if (error.code === "23505" && error.message.includes("join_code")) continue;
    return { error: mapError(error) };
  }
  return { error: "generic" };
}

export async function renameTable(
  _prev: TableActionState,
  formData: FormData,
): Promise<TableActionState> {
  const tableId = String(formData.get("tableId") ?? "");
  const label = String(formData.get("label") ?? "")
    .trim()
    .slice(0, MAX_LABEL);
  if (!label) return { error: "labelRequired" };

  const supabase = await createServerSupabase();
  if (!supabase || !tableId) return { error: "generic" };

  // RLS silently filters rows the user may not update, so check the row count.
  const { error, count } = await supabase
    .from("venue_tables")
    .update({ label }, { count: "exact" })
    .eq("id", tableId);
  if (error) return { error: mapError(error) };
  if (!count) return { error: "forbidden" };

  await revalidate();
  return { done: Date.now() };
}

export async function setTableActive(formData: FormData): Promise<void> {
  const tableId = String(formData.get("tableId") ?? "");
  const active = formData.get("active") === "true";

  const supabase = await createServerSupabase();
  if (!supabase || !tableId) return;

  await supabase.from("venue_tables").update({ is_active: active }).eq("id", tableId);
  await revalidate();
}
